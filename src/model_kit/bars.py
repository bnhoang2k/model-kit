"""Bars: reference pieces that new pieces are compared against.

A bar is a folder `NN-<name>/` holding a `bar.json` and the files it names. This module reads
that format strictly, finds the bars folder, picks the default bar per class, and renders the
generated `INDEX.md`. It reads only the bar files; it never opens a pack, a clip or a .glb.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Literal

from model_kit._shipped import ALLOW_SUFFIX, PRIVATE_BAR_FILE, SCENE_DIR, ships
from model_kit.core.errors import ManifestError
from model_kit.core.manifest.fields import (
    _At,
    _choice,
    _fields,
    _list,
    _name,
    _read_json,
    _text,
)

BarClass = Literal["assembly", "branching", "rigged"]
CLASSES: tuple[BarClass, ...] = ("assembly", "branching", "rigged")
INDEX_HEADER = "Generated by `model-kit bars`. Do not edit this file."

_SLUG = r"\d\d-[A-Za-z0-9][A-Za-z0-9_-]*"
_PIECE = r"[A-Za-z0-9_-]+:[A-Za-z0-9_.-]+"


@dataclass(frozen=True)
class Reference:
    """A source the bar follows: a public link (`url`) or a file the bar ships (`file`, a path
    inside the bar's folder), never both."""
    key: str
    gives: str
    url: str | None = None
    file: str | None = None


@dataclass(frozen=True)
class BarFiles:
    """The files a bar names. `allow` is optional: the gate allowlist (`check | item | reason`
    lines) for findings the bar keeps on purpose, beside bar.json."""
    style: str
    pack: str
    glb: str
    scene: str
    sheet: str
    allow: str | None = None


@dataclass(frozen=True)
class Bar:
    slug: str
    title: str
    cls: BarClass
    default: bool
    piece: str
    reads: str
    fits: str
    wrong_for: str
    references: tuple[Reference, ...]
    files: BarFiles
    superseded: str | None
    dir: Path

    def gate_args(self) -> list[str]:
        """The gate's arguments for this bar's whole scene: the scene folder, then `--allow` and
        the bar's allowlist when it has one."""
        args = [str(self.dir / self.files.scene)]
        if self.files.allow is not None:
            args += ["--allow", str(self.dir / self.files.allow)]
        return args


def _bool(at: _At, raw) -> bool:
    if not isinstance(raw, bool):
        at.fail(f"must be true or false, got {raw!r}")
    return raw


def _relative(at: _At, raw) -> str:
    name = _text(at, raw)
    if name.startswith("/") or ".." in Path(name).parts:
        at.fail(f"must be a path inside the bar's folder, got {name!r}")
    return name


def _reference(at: _At, raw, dir: Path) -> Reference:
    """A link or a shipped file: exactly one of `url` and `file`. A file must be in the bar's
    folder, outside its scene, of a suffix the bar ships, so the wheel carries it and the
    hygiene scan reads it."""
    raw = _fields(at, raw, ("key", "gives"), ("url", "file"))
    key, gives = _name(at.key("key"), raw["key"]), _text(at.key("gives"), raw["gives"])
    if ("url" in raw) == ("file" in raw):
        at.fail("needs exactly one of 'url' (a public link) and 'file' (a file the bar ships)")
    if "url" in raw:
        url = _text(at.key("url"), raw["url"])
        if not re.match(r"https?://\S+$", url):
            at.key("url").fail(f"must be an http(s) link, got {url!r}")
        return Reference(key, gives, url=url)
    file = _relative(at.key("file"), raw["file"])
    if Path(file).parts[0] == SCENE_DIR or not ships(Path(file)):
        at.key("file").fail(f"must be a file the bar ships, outside {SCENE_DIR}/, got {file!r}")
    if not (dir / file).is_file():
        at.key("file").fail(f"the file {file!r} is not in {dir}")
    return Reference(key, gives, file=file)


def load_bar(dir: Path) -> Bar:
    """Read one bar folder. Anything missing, unknown, repeated or misnamed raises."""
    dir = Path(dir)
    path = dir / "bar.json"
    if not path.is_file():
        raise ManifestError(f"{dir}: no bar.json in this bar folder")
    if (dir / PRIVATE_BAR_FILE).exists():
        raise ManifestError(
            f"{dir / PRIVATE_BAR_FILE}: a bar folder may not hold {PRIVATE_BAR_FILE}; "
            "notes kept on a bar live outside the bar folder")
    at = _At(path)
    raw = _fields(at, _read_json(path, "bar"),
                  ("slug", "title", "class", "default", "piece", "reads", "fits", "wrong_for",
                   "references", "files"), ("superseded",))
    slug = _text(at.key("slug"), raw["slug"])
    if not re.fullmatch(_SLUG, slug):
        at.key("slug").fail(f"must look like NN-<name>, got {slug!r}")
    if slug != dir.name:
        at.key("slug").fail(f"slug {slug!r} must equal the folder name {dir.name!r}")
    piece = _text(at.key("piece"), raw["piece"])
    if not re.fullmatch(_PIECE, piece):
        at.key("piece").fail(f"must be <pack>:<piece>, got {piece!r}")
    refs = tuple(_reference(at.key("references").index(i), r, dir) for i, r in
                 enumerate(_list(at.key("references"), raw["references"])))
    keys = [r.key for r in refs]
    if len(set(keys)) != len(keys):
        at.key("references").fail(f"keys repeat: {keys}")
    fat = at.key("files")
    fraw = _fields(fat, raw["files"], ("style", "pack", "glb", "scene", "sheet"), ("allow",))
    files = BarFiles(**{k: _relative(fat.key(k), fraw[k]) for k in fraw})
    if files.scene != SCENE_DIR:
        fat.key("scene").fail(f"must be {SCENE_DIR!r}, got {files.scene!r}")
    if files.allow is not None and (Path(files.allow).parts[0] == SCENE_DIR
                                    or Path(files.allow).suffix != ALLOW_SUFFIX
                                    or not ships(Path(files.allow))):
        fat.key("allow").fail(f"must be a {ALLOW_SUFFIX} file the bar ships, outside "
                              f"{SCENE_DIR}/ (a build replaces it), got {files.allow!r}")
    for field in ("style", "pack", "glb", "sheet", "allow"):
        if getattr(files, field) is None:
            continue
        if not (dir / getattr(files, field)).is_file():
            fat.key(field).fail(f"the file {getattr(files, field)!r} is not in {dir}")
    if (dir / files.scene).exists() and not (dir / files.scene).is_dir():
        fat.key("scene").fail(f"{files.scene!r} must be a folder")
    superseded = None
    if "superseded" in raw:
        superseded = _text(at.key("superseded"), raw["superseded"])
    return Bar(slug, _text(at.key("title"), raw["title"]), _choice(at.key("class"), raw["class"], CLASSES),
               _bool(at.key("default"), raw["default"]), piece,
               _text(at.key("reads"), raw["reads"]), _text(at.key("fits"), raw["fits"]),
               _text(at.key("wrong_for"), raw["wrong_for"]), refs, files, superseded, dir)


def bars_root(override: Path | None = None, flag: str = "--bars") -> Path:
    """The bars folder: the override, else MODEL_KIT_BARS, else the shipped copy, else the source
    tree. `flag` names the command-line option the override came from, for the error."""
    for source, value in ((flag, override), ("MODEL_KIT_BARS", os.environ.get("MODEL_KIT_BARS"))):
        if value:
            root = Path(value)
            if not root.is_dir():
                raise ManifestError(f"{source} names {root}, which is not a folder")
            return root
    shipped = Path(str(resources.files("model_kit") / "_bars"))
    if shipped.is_dir():
        return shipped
    tree = Path(__file__).resolve().parents[2] / "bars"
    if tree.is_dir():
        return tree
    raise ManifestError("no bars folder found: pass --bars <folder> or set MODEL_KIT_BARS")


def read_bars(root: Path) -> list[Bar]:
    """Every `*/bar.json` under root, in folder order. Each class with live bars has one default."""
    bars = [load_bar(p.parent) for p in sorted(Path(root).glob("*/bar.json"))]
    for cls in CLASSES:
        live = [b for b in bars if b.cls == cls and b.superseded is None]
        defaults = [b.slug for b in live if b.default]
        if live and len(defaults) != 1:
            raise ManifestError(
                f"{root}: class {cls!r} needs exactly one default bar among {[b.slug for b in live]}, "
                f"found {len(defaults)}: {defaults}")
    return bars


def bar_for(cls: str, bars: list[Bar]) -> Bar:
    """The default live bar of a class."""
    for bar in bars:
        if bar.cls == cls and bar.default and bar.superseded is None:
            return bar
    raise ManifestError(f"no bar for {cls} pieces; pass --bar none")


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_index(bars: list[Bar]) -> str:
    """The text of INDEX.md: one section per class that has live bars, one row per live bar."""
    out = [INDEX_HEADER, ""]
    for cls in CLASSES:
        live = [b for b in bars if b.cls == cls and b.superseded is None]
        if not live:
            continue
        out += [f"## {cls}", "",
                "| Bar | Title | Default | Piece | Reads | Fits | Wrong for | Folder |",
                "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for b in live:
            out.append(f"| [{b.slug}]({b.slug}/) | {_cell(b.title)} | {'yes' if b.default else 'no'} "
                       f"| `{b.piece}` | {_cell(b.reads)} | {_cell(b.fits)} | {_cell(b.wrong_for)} "
                       f"| `bars/{b.slug}/` |")
        out.append("")
    return "\n".join(out)
